"""Assemble the Hugging Face Space from this folder, so the Space never installs from GitHub.

The repo is private, so the Space cannot `pip install git+https://github.com/...` any more.
Instead the Space gets a copy of the package next to app.py, and a requirements.txt made from
pyproject.toml's dependencies. The sync-space workflow runs this and uploads the result.

    python analyst-service/space/build.py <out_dir>
"""

import shutil
import sys
import tomllib
from pathlib import Path

SPACE = Path(__file__).resolve().parent
SERVICE = SPACE.parent


def build(out: Path) -> None:
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for name in ("README.md", "app.py"):
        shutil.copy2(SPACE / name, out / name)
    shutil.copytree(
        SERVICE / "openstock_analyst",
        out / "openstock_analyst",
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
    )
    deps = tomllib.loads((SERVICE / "pyproject.toml").read_text())["project"]["dependencies"]
    (out / "requirements.txt").write_text(
        "# Generated by analyst-service/space/build.py from pyproject.toml; do not edit in the Space\n"
        + "\n".join(deps)
        + "\n"
    )


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: build.py <out_dir>")
    build(Path(sys.argv[1]))
